function appendWalkingGuide(node,plan){
  const info=WALKING_GUIDE[plan.id];
  if(!info)return;
  const original=defaults.days.flatMap(d=>d.plans).find(p=>p.id===plan.id);
  const box=document.createElement('details');box.className='walking-guide';
  const summary=document.createElement('summary');summary.textContent='도보 · '+info[2];box.appendChild(summary);
  const route=document.createElement('p');route.textContent=info[0]+' | '+info[1];box.appendChild(route);
  const note=document.createElement('p');note.textContent=info[3];box.appendChild(note);
  const disclaimer=document.createElement('small');disclaimer.textContent='기본 일정의 계획용 추정치 · 실측/실시간 길찾기 아님. 거리·출입구·혼잡에 따라 변동. 일정이나 순서를 수정하면 직접 재확인하세요.';box.appendChild(disclaimer);
  if(original&&(original.name!==plan.name||original.map!==plan.map)){
    summary.textContent='도보 참고 · 원래 장소 기준 (수정한 장소는 재확인)';
  }
  node.querySelector('.plan-note').after(box);
}
