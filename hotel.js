function updateHotelTripData(data){
  const u=HOTEL_TRIP_UPDATE;
  data.lodging=JSON.parse(JSON.stringify(u.lodging));
  for(const day of data.days){
    for(const plan of day.plans){if(u.plans[plan.id])Object.assign(plan,JSON.parse(JSON.stringify(u.plans[plan.id])));}
    for(const entry of u.insertions[day.date]||[]){
      if(day.plans.some(p=>p.id===entry.plan.id))continue;
      const index=day.plans.findIndex(p=>p.id===(entry.before||entry.after));
      day.plans.splice(index<0?day.plans.length:index+(entry.after?1:0),0,JSON.parse(JSON.stringify(entry.plan)));
    }
    day.notes=(day.notes||[]).filter(n=>!(u.removeNotes[day.date]||[]).includes(n));
    for(const n of u.notes[day.date]||[]){if(!day.notes.includes(n))day.notes.push(n);}
  }
  if(data.preTripChecklist){
    const old=data.preTripChecklist.find(i=>i.id===u.pre.id);
    if(old)Object.assign(old,u.pre);else data.preTripChecklist.push(JSON.parse(JSON.stringify(u.pre)));
  }
  if(data.dailyChecklist){
    for(const group of data.dailyChecklist){
      for(const item of group.items){if(u.checks[item.id]){item.text=u.checks[item.id];if(/^d[234]-seven-atm-check$/.test(item.id)){item.url='https://location.sevenbank.co.jp/sevenbank/spot/detail?code=0000007338';}}}
      for(const item of u.extraChecks[group.date]||[]){if(!group.items.some(i=>i.id===item.id))group.items.push(JSON.parse(JSON.stringify(item)));}
    }
  }
  return data;
}
